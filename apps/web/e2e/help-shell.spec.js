import { test, expect } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { startTeachingAuth } from './teaching-time-auth/service.mjs';
import { register } from './teaching-time-auth/helpers.mjs';
let world, directory;
test.beforeEach(async ({ page }) => {
  world = undefined;
  directory = fs.mkdtempSync(path.join(os.tmpdir(), 'help-shell-'));
  world = await startTeachingAuth({ directory });
  await register(page, world);
  const coach = page.getByRole('button', { name: /知道了/ });
  if (await coach.count()) await coach.first().click();
  await page.goto(world.origin + '/help');
  await expect(page.getByRole('heading', { name: '有什么可以帮您？' })).toBeVisible();
});
test.afterEach(async ({}, info) => {
  await world?.close();
  if (info.status === info.expectedStatus) fs.rmSync(directory, { recursive: true, force: true });
  else console.error('Test instance retained:', directory);
});
test('帮助首页、目录、深链接和返回；更新日志只有图标', async ({ page }, testInfo) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await expect(page.locator('.help-topic-card')).toHaveCount(6);
  await page.screenshot({ animations: 'disabled', path: testInfo.outputPath('desktop.png') });
  await page.locator('.help-topic-card').filter({ hasText: '数学工坊' }).click();
  await expect(page).toHaveURL(/\/help\/math$/);
  await expect(page.getByRole('heading', { name: '本章内容' })).toBeVisible();
  await expect(page.getByRole('button', { name: '数学工坊', exact: true })).toHaveAttribute('aria-expanded', 'true');
  await page.locator('.help-article-card').filter({ hasText: '下载与离线使用' }).click();
  await expect(page).toHaveURL(/\/help\/math\/2$/);
  await page.reload();
  await expect(page.getByRole('heading', { name: '下载与离线使用', exact: true })).toBeVisible();
  await expect(page.locator('.help-article')).toContainText('SVG');
  await page.screenshot({ animations: 'disabled', path: testInfo.outputPath('article.png') });
  await page.getByRole('link', { name: '帮助', exact: true }).click();
  await expect(page.getByRole('heading', { name: '热门主题' })).toBeVisible();
  await page.goBack();
  await expect(page.getByRole('heading', { name: '下载与离线使用', exact: true })).toBeVisible();
  await page.getByRole('link', { name: '进入数学工坊', exact: true }).click();
  await expect(page).toHaveURL(/\/math$/);
  await page.goto(world.origin + '/help/missing/article');
  await expect(page.getByRole('heading', { name: '未找到这篇文章' })).toBeVisible();
  await page.goto(world.origin + '/releases');
  const releases = page.locator('[data-region="releases"]');
  await expect(releases).toHaveText('');
  await expect(releases.locator('svg')).toBeVisible();
  await page.screenshot({ animations: 'disabled', path: testInfo.outputPath('releases.png') });
  expect(errors).toEqual([]);
});
test('搜索支持关键词、键盘、空结果和退出动效', async ({ page }, testInfo) => {
  await page.getByRole('textbox', { name: '搜索文章', exact: true }).fill('SVG');
  await page.getByRole('button', { name: '搜索', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '搜索帮助文档' });
  await expect(dialog).toBeVisible();
  await expect(page.getByRole('option')).toHaveCount(1);
  await page.keyboard.press('Enter');
  await expect(page.getByRole('heading', { name: '下载与离线使用', exact: true })).toBeVisible();
  await expect(dialog).toHaveCount(0);
  await page.keyboard.press('Control+k');
  await expect(dialog).toBeVisible();
  const input = page.getByRole('combobox', { name: '搜索帮助文档' });
  await input.fill('不存在的词');
  await expect(dialog).toContainText('未找到相关文章');
  await input.fill('保存');
  await expect(page.getByRole('option').first()).toBeVisible();
  await page.keyboard.press('ArrowDown');
  await expect(input).toHaveAttribute('aria-activedescendant', 'help-result-1');
  await page.screenshot({ animations: 'disabled', path: testInfo.outputPath('search.png') });
  await page.evaluate(() => {
    window.helpFrames = [];
    const sample = () => { const node = document.querySelector('.help-search-dialog'); helpFrames.push(node ? Number(getComputedStyle(node).opacity) : -1); if (helpFrames.length < 60) requestAnimationFrame(sample); };
    requestAnimationFrame(sample);
  });
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  expect(await page.evaluate(() => helpFrames.some(value => value > 0 && value < 1))).toBe(true);
  await page.keyboard.press('Control+k'); await page.keyboard.press('Control+k'); await page.keyboard.press('Control+k');
  await expect(dialog).toBeVisible();
  await expect(input).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(dialog).toHaveCount(0);
});
test('窄屏目录连续展开收起，正文无溢出', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const help = page.locator('[data-region="help"]');
  await page.screenshot({ animations: 'disabled', path: testInfo.outputPath('mobile.png') });
  const toggle = page.getByRole('button', { name: '帮助目录', exact: true });
  await toggle.click();
  const topic = page.getByRole('button', { name: '题库', exact: true });
  await topic.click();
  await expect(page.getByRole('link', { name: '自建题目' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: '有什么可以帮您？' })).toBeVisible();
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await expect(toggle).toHaveAttribute('aria-expanded', 'true');
  await expect(page.getByRole('link', { name: '自建题目' })).toBeVisible();
  await topic.click(); await topic.click();
  await expect(topic).toHaveAttribute('aria-expanded', 'true');
  await page.getByRole('link', { name: '自建题目' }).click();
  await expect(page.getByRole('heading', { name: '自建题目' })).toBeVisible();
  await expect(toggle).toHaveAttribute('aria-expanded', 'false');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(await help.evaluate(e => e.scrollWidth <= e.clientWidth + 1)).toBe(true);
  await toggle.click();
  await page.getByRole('button', { name: /搜索…/ }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: /搜索…/ })).toBeFocused();
});
