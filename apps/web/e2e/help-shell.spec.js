test('搜索支持关键词、键盘、空结果和快捷键切换', async ({ page }, testInfo) => {
  await page.getByRole('button', { name: '搜索帮助文章' }).click();
  const dialog = page.getByRole('dialog', { name: '搜索帮助文章' });
  const input = dialog.getByRole('combobox');
  await expect(dialog).toBeVisible();
  await input.fill('SVG');
  await expect(page.getByRole('option')).toHaveCount(1);
  await page.keyboard.press('Enter');
  await expect(page.getByRole('heading', { name: '导出到课件', exact: true })).toBeVisible();
  await expect(dialog).toHaveCount(0);
  await page.keyboard.press('Control+k');
  await expect(dialog).toBeVisible();
  await input.fill('不存在的词');
  await expect(dialog).toContainText('没有找到');
  await input.fill('保存');
  await expect(page.getByRole('option').first()).toBeVisible();
  await expect(page.getByRole('option').filter({ hasText: '录入一道题' })).not.toContainText('question');
  await page.keyboard.press('ArrowDown');
  await expect(input).toHaveAttribute('aria-activedescendant', 'tbx-hs-1');
  await page.screenshot({ animations: 'disabled', path: testInfo.outputPath('search.png') });
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await page.keyboard.press('Control+k'); await page.keyboard.press('Control+k'); await page.keyboard.press('Control+k');
  await expect(dialog).toBeVisible();
  await expect(input).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(dialog).toHaveCount(0);
});
