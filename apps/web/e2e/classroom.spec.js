test('另一页改名后归档冲突会提示并重读，只有重新主动确认才归档', async ({ page, context }, info) => {
  const errors = [], deletionBodies = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => {
    if (request.method() === 'PUT' && /\/classes\/[^/]+\/deletion$/.test(new URL(request.url()).pathname)) deletionBodies.push(request.postDataJSON());
  });
  await register(page, world, 'classroom-conflict@example.test');
  const coach = page.getByRole('button', { name: /知道了/ });
  if (await coach.count()) await coach.first().click();
  await page.goto(world.origin + '/classroom');
  await page.locator('.cr-empty').getByRole('button', { name: '新建班级', exact: true }).click();
  await page.getByRole('dialog').getByLabel('班级名称', { exact: true }).fill('并发改名前');
  await page.getByRole('dialog').getByRole('button', { name: '创建班级', exact: true }).click();
  await expect(page.getByRole('heading', { name: '并发改名前', exact: true })).toBeVisible();
  const cls = (await read(page, 'classes')).items[0];
  const other = await context.newPage();
  await other.goto(world.origin + '/classroom');
  await expect(other.getByRole('heading', { name: '并发改名前', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '班级操作', exact: true }).click();
  await page.getByRole('menuitem', { name: '归档班级', exact: true }).click();
  await expect(page.getByRole('alertdialog')).toContainText('并发改名前');
  await other.getByRole('button', { name: '班级操作', exact: true }).click();
  await other.getByRole('menuitem', { name: '班级信息', exact: true }).click();
  await other.getByRole('dialog').getByLabel('班级名称', { exact: true }).fill('另一页更新后的班级');
  await other.getByRole('dialog').getByRole('button', { name: '保存', exact: true }).click();
  await expect(other.getByRole('heading', { name: '另一页更新后的班级', exact: true })).toBeVisible();
  const rejected = page.waitForResponse(response => response.request().method() === 'PUT' && response.url().endsWith(`/classes/${cls.id}/deletion`));
  await page.getByRole('alertdialog').getByRole('button', { name: '归档', exact: true }).click();
  expect((await rejected).status()).toBe(409);
  await expect(page.locator('.cr-toast.is-error')).toContainText('服务器版本 2');
  await expect(page.getByRole('alertdialog')).toHaveCount(0);
  await expect(page.getByRole('heading', { name: '另一页更新后的班级', exact: true })).toBeVisible();
  expect((await read(page, `classes/${cls.id}`)).deletedAt).toBeNull();
  expect(deletionBodies).toEqual([{ baseVersion: 1, deleted: true }]);
  expect(errors).toEqual([]);
  await page.screenshot({ path: info.outputPath('archive-conflict-reloaded.png'), animations: 'disabled' });
  await page.getByRole('button', { name: '班级操作', exact: true }).click();
  await page.getByRole('menuitem', { name: '归档班级', exact: true }).click();
  await expect(page.getByRole('alertdialog')).toContainText('另一页更新后的班级');
  await page.getByRole('alertdialog').getByRole('button', { name: '归档', exact: true }).click();
  await expect(page.getByRole('heading', { name: '把你教的班级放在这里' })).toBeVisible();
  expect((await read(page, `classes/${cls.id}`)).deletedAt).not.toBeNull();
  expect(deletionBodies).toEqual([{ baseVersion: 1, deleted: true }, { baseVersion: 2, deleted: true }]);
  expect(errors).toEqual([]);
  await other.close();
});


