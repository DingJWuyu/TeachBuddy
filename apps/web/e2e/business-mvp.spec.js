test('平面函数与空间图形可制作、保存、刷新及下载',async({page})=>{
 await register(page);
 await nav(page,'数学工坊');
 await page.getByRole('button',{name:'新建平面图形',exact:true}).first().click();
 await page.getByRole('button',{name:'作品与工具',exact:true}).click();
 await page.getByLabel('作品名称').fill('二次函数图像');
 await page.getByRole('button',{name:'添加函数',exact:true}).click();
 await page.getByLabel('expression',{exact:true}).fill('x^2-2*x-3');
 await page.getByRole('button',{name:'保存',exact:true}).click();
 await expect(page.getByRole('status').first()).toContainText('已保存');
 await page.reload();
 await expect(page.getByLabel('expression',{exact:true})).toHaveValue('x^2-2*x-3');
 for(const format of ['png','svg','source']) {
  await page.getByLabel('导出格式').selectOption(format);
  const waiting=page.waitForEvent('download');
  await page.getByRole('button',{name:'下载',exact:true}).click();
  const target=path.join(evidence,`function.${format==='source'?'json':format}`);
  await (await waiting).saveAs(target);
  expect(fs.statSync(target).size).toBeGreaterThan(100);
 }
 await page.screenshot({path:path.join(evidence,'function-editor.png'),animations:'disabled'});
 await page.getByRole('button',{name:'新建空间图形',exact:true}).click();
 await page.getByRole('button',{name:'正方体起点',exact:true}).click();
 await page.getByLabel('作品名称').fill('正方体示意图');
 await page.getByLabel('azimuth',{exact:true}).fill('45');
 await page.getByRole('button',{name:'保存',exact:true}).click();
 await expect(page.getByRole('status').first()).toContainText('已保存');
 await page.reload();
 await expect(page.getByLabel('azimuth',{exact:true})).toHaveValue('45');
 await page.getByLabel('导出格式').selectOption('svg');
 const waiting=page.waitForEvent('download');
 await page.getByRole('button',{name:'下载',exact:true}).click();
 await (await waiting).saveAs(path.join(evidence,'cube.svg'));
 await page.screenshot({path:path.join(evidence,'cube.png'),animations:'disabled'});
});
